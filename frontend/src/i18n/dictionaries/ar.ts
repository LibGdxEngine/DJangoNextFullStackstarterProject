const n2 = (n: number) => new Intl.NumberFormat("ar-EG").format(n);

/** Arabic counts: 1 → singular, 2 → dual, 3–10 → plural, 11+ → singular (tamyeez). */
const count = (n: number, one: string, two: string, few: string, many: string = one) => {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return `${n2(n)} ${few}`;
  return `${n2(n)} ${many}`;
};

