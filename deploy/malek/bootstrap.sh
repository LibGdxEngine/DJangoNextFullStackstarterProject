#!/bin/sh
# Idempotent host setup for the Imam Malek Academy deployment. Root only. Safe to rerun on every push.
set -eu
export PATH=/usr/sbin:/usr/bin:/sbin:/bin
BASE=${MALEK_BASE:-/srv/malek-academy}
PUBLIC_HOST=${MALEK_PUBLIC_HOST:-malek.ic-mobile.tech}
SRC="$BASE/src"
test "$(id -u)" = 0 || { echo "root required" >&2; exit 1; }
umask 077
mkdir -p "$BASE" "$BASE/backups"
chmod 700 "$BASE" "$BASE/backups"
# Reviewed runtime definition, copied verbatim from the repository.
cp "$SRC/deploy/compose.yml" "$BASE/compose.yml"
cp "$SRC/deploy/gateway.Caddyfile" "$BASE/gateway.Caddyfile"
# Replace via rename, never in place: receive.sh is executing from $BASE while this runs.
for f in receive.sh redeploy.sh rollback.sh caddy-ensure.sh caddy-site.caddy; do
    cp "$SRC/deploy/malek/$f" "$BASE/.$f.new"
    mv -f "$BASE/.$f.new" "$BASE/$f"
done
chmod 755 "$BASE/receive.sh" "$BASE/redeploy.sh" "$BASE/rollback.sh" "$BASE/caddy-ensure.sh"
chmod 644 "$BASE/compose.yml" "$BASE/gateway.Caddyfile" "$BASE/caddy-site.caddy"
if [ ! -f "$BASE/runtime.env" ]; then
    rand() { openssl rand -hex "$1"; }
    cat > "$BASE/runtime.env" <<ENV
# Generated by deploy/malek/bootstrap.sh; secrets are unique to this host.
COMPOSE_PROJECT_NAME=malek-academy
EDGE_NETWORK=malek_academy_edge
EDGE_ALIAS=malek-academy-gateway
GATEWAY_PORT=18100
DB_NAME=malek_academy
DB_USER=malek_academy
DB_PASSWORD=$(rand 24)
SECRET_KEY=$(rand 48)
OTP_SECRET=$(rand 32)
NEXTAUTH_SECRET=$(rand 32)
NEXTAUTH_URL=https://$PUBLIC_HOST
ALLOWED_HOSTS=$PUBLIC_HOST,localhost,backend
CORS_ALLOWED_ORIGINS=https://$PUBLIC_HOST
CSRF_TRUSTED_ORIGINS=https://$PUBLIC_HOST
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
# Delivery is not configured yet: mail is discarded and HireAgents points at a black hole.
# To enable, set EMAIL_BACKEND/EMAIL_* or the HIREAGENTS_* values here, then rerun redeploy.sh.
DEFAULT_FROM_EMAIL=no-reply@$PUBLIC_HOST
EMAIL_BACKEND=django.core.mail.backends.dummy.EmailBackend
HIREAGENTS_BASE_URL=http://127.0.0.1:9
HIREAGENTS_AUTH_CHANNEL_ID=
HIREAGENTS_AUTH_API_KEY=
HIREAGENTS_SUPPORT_CHANNEL_ID=
HIREAGENTS_SUPPORT_API_KEY=
HIREAGENTS_AUTH_WEBHOOK_API_KEY=$(rand 24)
HIREAGENTS_AUTH_WEBHOOK_SIGNING_SECRET=$(rand 32)
HIREAGENTS_SUPPORT_WEBHOOK_API_KEY=$(rand 24)
HIREAGENTS_SUPPORT_WEBHOOK_SIGNING_SECRET=$(rand 32)
ENV
    echo "generated $BASE/runtime.env"
fi
chmod 600 "$BASE/runtime.env"
docker network inspect malek_academy_edge >/dev/null 2>&1 || docker network create malek_academy_edge >/dev/null
# Self-healing attachment to the company Caddy (its container is recreated on company releases).
cp "$SRC/deploy/malek/malek-academy-caddy-ensure.service" /etc/systemd/system/
cp "$SRC/deploy/malek/malek-academy-caddy-ensure.timer" /etc/systemd/system/
chmod 644 /etc/systemd/system/malek-academy-caddy-ensure.service /etc/systemd/system/malek-academy-caddy-ensure.timer
systemctl daemon-reload
systemctl enable --now malek-academy-caddy-ensure.timer >/dev/null 2>&1
echo "bootstrap ok: $BASE"
